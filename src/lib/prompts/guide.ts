/**
 * 构建 Prompt 3 的用户消息（注入变量）
 */
export function buildGuideUserMessage(params: {
  stage: string
  checkInCount: number
  stageAnswersSummary: string
}): string {
  return `# 当前上下文
当前阶段：${params.stage}
本阶段打卡次数：${params.checkInCount}
本阶段所有打卡回答汇总：
${params.stageAnswersSummary}`
}
