/**
 * 构建 Prompt 2 的用户消息（注入变量）
 */
export function buildDialogueUserMessage(params: {
  article: string
  question: string
  userAnswer: string
  dialogueHistory: { role: string; content: string }[]
  round: number
}): string {
  const historyText = params.dialogueHistory.length > 0
    ? JSON.stringify(params.dialogueHistory, null, 2)
    : '（暂无历史，这是第一轮追问）'

  const roundLabel =
    params.round === 5
      ? '5（总结轮：用户已回答总结性问题，请输出收尾内容，follow_up_question 为空字符串，is_final_round 为 true）'
      : params.round === 4
        ? '4（总结性问题轮：请提出总结性问题，不输出收尾字段）'
        : String(params.round)

  return `# 当前上下文
文章内容：${params.article}
思考题：${params.question}
用户回答：${params.userAnswer}
对话历史：${historyText}
当前轮次：${roundLabel}`
}
